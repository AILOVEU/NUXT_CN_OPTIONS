// 用确定性伪随机生成一段看似合理的盈亏曲线（不依赖真实数据）
function 生成Mock日线(数量, 起始日, 起始值) {
  const 结果 = [];
  let 当前 = 起始值;
  let 游标 = dayjs(起始日, "YYYYMMDD");
  // 简单线性同余伪随机，保证每次运行结果一致
  let seed = Date.now() % 233280 || 1;
  const rand = () => {
    seed = (seed * 9301 + 49297) % 233280;
    return seed / 233280;
  };
  for (let i = 0; i < 数量; i++) {
    // 跳过户非交易日（周末），仅作粗略模拟
    while (游标.day() === 0 || 游标.day() === 6) {
      游标 = 游标.add(1, "day");
    }
    const 波动 = Math.round((rand() - 0.45) * 8000);
    当前 = 当前 + 波动;
    结果.push([游标.format("YYYYMMDD"), 当前]);
    游标 = 游标.add(1, "day");
  }
  return 结果;
}

